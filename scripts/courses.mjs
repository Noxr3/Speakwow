#!/usr/bin/env node
// Courses are a small wiki in courses/: one folder per course with an
// index.md (the course and a generated list of units), a log.md of changes,
// and one Markdown page per unit. The structured part of each page, the part
// the teacher scores and the app stores, sits in its YAML front matter and is
// checked against courses/schema/*.schema.json; the body is free teaching
// notes. courses/AGENTS.md has the rules for people and AI agents.
//
//   pnpm courses:check            check every course (CI runs this)
//   pnpm courses:index            rewrite each index.md's unit list
import Ajv2020 from 'ajv/dist/2020.js';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse as parseYaml } from 'yaml';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', 'courses');
const UNIT_FILE = /^(\d{2})-[a-z0-9]+(-[a-z0-9]+)*\.md$/;
const LIST_FIELDS = ['terms', 'points', 'activities', 'pitfalls'];
// A paragraph this long in a page is more likely a pasted passage than a note.
const MAX_PARAGRAPH = 600;
const START = '<!-- units:start (generated by pnpm courses:index; do not edit) -->';
const END = '<!-- units:end -->';

const ajv = new Ajv2020({ allErrors: true, strict: false });
const schema = (name) =>
  JSON.parse(readFileSync(join(ROOT, 'schema', `${name}.schema.json`), 'utf8'));
const validateCourse = ajv.compile(schema('course'));
const validateUnit = ajv.compile(schema('unit'));

/** {data, body} from a Markdown page with YAML front matter. */
export function parsePage(text) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/.exec(text);
  if (!match) return { data: null, body: text };
  return { data: parseYaml(match[1]) ?? {}, body: match[2] };
}

function schemaErrors(validate, data, where) {
  if (validate(data)) return [];
  return validate.errors.map((e) => `${where}: ${e.instancePath || '(page)'} ${e.message}`);
}

/** The course folder's index, units and log, read but not checked. */
export function loadCourse(dir) {
  const slug = basename(dir);
  const index = existsSync(join(dir, 'index.md'))
    ? parsePage(readFileSync(join(dir, 'index.md'), 'utf8'))
    : null;
  const unitsDir = join(dir, 'units');
  const files = existsSync(unitsDir)
    ? readdirSync(unitsDir)
        .filter((f) => f.endsWith('.md'))
        .sort()
    : [];
  const units = files.map((file) => ({
    file,
    ...parsePage(readFileSync(join(unitsDir, file), 'utf8')),
  }));
  return { dir, slug, index, units, hasLog: existsSync(join(dir, 'log.md')) };
}

/** The generated unit list that sits between the markers in index.md. */
export function unitTable(units) {
  const rows = units
    .filter((u) => u.data)
    .sort((a, b) => a.data.position - b.data.position)
    .map((u) => {
      const d = u.data;
      const title = d.subtitle ? `${d.title}（${d.subtitle}）` : d.title;
      return `| ${d.position} | [${title}](units/${u.file}) | ${d.theme ?? ''} | ${d.goals?.length ?? 0} | ${d.review?.status ?? ''} |`;
    });
  return [
    START,
    '| # | Unit | Theme | Goals | Review |',
    '|---|---|---|---|---|',
    ...rows,
    END,
  ].join('\n');
}

function withTable(body, units) {
  const start = body.indexOf('<!-- units:start');
  const end = body.indexOf(END);
  if (start === -1 || end === -1) return null;
  return body.slice(0, start) + unitTable(units) + body.slice(end + END.length);
}

/** Everything wrong with one course, as readable lines; empty when fine. */
export function checkCourse(course) {
  const problems = [];
  const at = (file) => `${course.slug}/${file}`;
  if (!course.index?.data) {
    problems.push(`${at('index.md')}: missing, or has no front matter`);
  } else {
    problems.push(...schemaErrors(validateCourse, course.index.data, at('index.md')));
    if (course.index.data.slug !== course.slug) {
      problems.push(
        `${at('index.md')}: slug "${course.index.data.slug}" must be the folder name "${course.slug}"`
      );
    }
    const expected = withTable(course.index.body, course.units);
    if (expected === null)
      problems.push(`${at('index.md')}: the units:start / units:end markers are missing`);
    else if (expected !== course.index.body) {
      problems.push(`${at('index.md')}: the unit list is out of date; run pnpm courses:index`);
    }
  }
  if (!course.hasLog) problems.push(`${at('log.md')}: missing; every course keeps a change log`);
  if (!course.units.length) problems.push(`${at('units/')}: no unit pages`);

  const positions = [];
  for (const unit of course.units) {
    const where = at(`units/${unit.file}`);
    const name = UNIT_FILE.exec(unit.file);
    if (!name)
      problems.push(`${where}: name it NN-short-title.md, e.g. 03-welcome-to-our-school.md`);
    if (!unit.data) {
      problems.push(`${where}: has no front matter`);
      continue;
    }
    problems.push(...schemaErrors(validateUnit, unit.data, where));
    const { position, goals = [] } = unit.data;
    positions.push(position);
    if (name && Number(name[1]) !== position) {
      problems.push(`${where}: position ${position} does not match the file number ${name[1]}`);
    }
    const ids = new Set();
    for (const goal of goals) {
      if (!goal?.id) continue;
      if (!goal.id.startsWith(`u${position}-`)) {
        problems.push(`${where}: goal ${goal.id} must start with u${position}-`);
      }
      if (ids.has(goal.id)) problems.push(`${where}: goal id ${goal.id} is used twice`);
      ids.add(goal.id);
    }
    for (const field of LIST_FIELDS) {
      const seen = new Set();
      for (const item of unit.data[field] ?? []) {
        const key = String(item).trim().toLowerCase();
        if (seen.has(key)) problems.push(`${where}: "${item}" appears twice in ${field}`);
        seen.add(key);
      }
    }
    for (const paragraph of unit.body.split(/\n\s*\n/)) {
      if (paragraph.trim().length > MAX_PARAGRAPH) {
        problems.push(
          `${where}: a paragraph of ${paragraph.trim().length} characters; pages hold outlines and notes, never textbook text`
        );
      }
    }
  }
  const sorted = [...positions].sort((a, b) => a - b);
  if (sorted.some((p, i) => p !== i + 1)) {
    problems.push(
      `${at('units/')}: positions must run 1, 2, 3… without gaps or repeats (found ${sorted.join(', ')})`
    );
  }
  return problems;
}

export function courseDirs(root = ROOT) {
  return readdirSync(root, { withFileTypes: true })
    .filter((e) => e.isDirectory() && e.name !== 'schema')
    .map((e) => join(root, e.name))
    .sort();
}

/** A course as rows for the courses and course_units tables. */
export function toRows(course) {
  const d = course.index.data;
  return {
    course: {
      slug: d.slug,
      title: d.title,
      description: d.description ?? null,
      subject: d.subject,
      grade: d.grade ?? null,
      term: d.term ?? null,
      region: d.region ?? null,
      publisher: d.publisher ?? null,
      edition: d.edition ?? null,
      standard: d.standard ?? null,
      source: 'repo',
      source_ref: `courses/${d.slug}`,
    },
    units: [...course.units]
      .sort((a, b) => a.data.position - b.data.position)
      .map((u) => ({
        position: u.data.position,
        title: u.data.title,
        theme: u.data.theme ?? null,
        topic: u.data.topic ?? null,
        goals: u.data.goals,
        content: {
          ...Object.fromEntries(LIST_FIELDS.map((f) => [f, u.data[f] ?? []])),
          sources: u.data.sources ?? [],
        },
        source_ref: `courses/${d.slug}/units/${u.file}`,
      })),
  };
}

function main() {
  const [command, ...dirs] = process.argv.slice(2);
  const targets = dirs.length ? dirs : courseDirs();
  if (command === 'index') {
    for (const dir of targets) {
      const course = loadCourse(dir);
      const body = course.index && withTable(course.index.body, course.units);
      if (body === null || !course.index) {
        console.error(`${course.slug}: index.md needs the units:start / units:end markers`);
        process.exitCode = 1;
        continue;
      }
      const text = readFileSync(join(dir, 'index.md'), 'utf8');
      writeFileSync(
        join(dir, 'index.md'),
        text.slice(0, text.length - course.index.body.length) + body
      );
      console.log(`${course.slug}: unit list updated`);
    }
    return;
  }
  if (command !== 'check') {
    console.error('usage: courses.mjs check|index [courses/<slug> ...]');
    process.exit(2);
  }
  let total = 0;
  for (const dir of targets) {
    const course = loadCourse(dir);
    const problems = checkCourse(course);
    total += problems.length;
    console.log(
      problems.length ? problems.join('\n') : `${course.slug}: ok (${course.units.length} units)`
    );
  }
  if (total) {
    console.error(`\n${total} problem${total === 1 ? '' : 's'}. The rules: courses/AGENTS.md`);
    process.exit(1);
  }
}

if (import.meta.url === `file://${process.argv[1]}`) main();
